#!/usr/bin/env python3
"""Rebuild performance.css, the design layer behind Settings > Display > Graphics quality (graphics.js).

It is generated from the other layers, so that Balanced and Low switch off exactly the effects those
layers add and nothing of SillyTavern's own: every rule that blurs what is behind it, and every
animation that is nothing but a loop. Run it after adding a backdrop-filter or a looping animation
to any layer, then run tools/build-css.py. tools/build-css.py appends performance.css last.
"""
import importlib.util
import pathlib
import re

EXT = pathlib.Path(__file__).resolve().parent.parent / 'extension' / 'genshin-dialogue-ui'
MARK = '\n/* @@silly-teyvat-1.19-ui@@ */\n'
OUT = 'performance.css'


def sources():
    base = (EXT / 'style.css').read_text()
    base = base[:base.index(MARK)] if MARK in base else base
    spec = importlib.util.spec_from_file_location('build_css', pathlib.Path(__file__).with_name('build-css.py'))
    layers = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(layers)
    return base + '\n'.join((EXT / layer).read_text() for layer in layers.LAYERS if layer != OUT)


def parts(selector):
    return [re.sub(r'\s+', ' ', part.strip()) for part in re.split(r',\s*(?![^()]*\))', selector) if part.strip()]


def scoped(selector, name):
    if re.match(r'^body(?=[\s.#:\[>]|$)', selector):
        return re.sub(r'^body', f'body.{name}', selector)
    if selector.startswith(':root') or selector.startswith('html'):
        return None
    return f'body.{name} {selector}'


def rules(css):
    """Yield (selector, declarations) for style rules, including those inside @media and @supports."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    for match in re.finditer(r'([^{};]+)\{([^{}]*)\}', css):
        selector = match.group(1).strip()
        if selector and not selector.startswith('@') and not re.match(r'^(from|to|[\d.]+%)', selector):
            yield selector, match.group(2)


def main():
    blurs, loops = [], []
    for selector, body in rules(sources()):
        if re.search(r'backdrop-filter\s*:\s*(?!none)', body):
            blurs += parts(selector)
        for value in re.findall(r'animation\s*:\s*([^;]+)', body):
            # A loop on its own: nothing waits for it to end. A loop that follows an entrance is left alone.
            if 'infinite' in value and ',' not in value:
                loops += parts(selector)
    blur = [s for s in dict.fromkeys(scoped(s, 'gi-gfx-balanced') for s in blurs) if s]
    loop = [s for s in dict.fromkeys(scoped(s, 'gi-gfx-low') for s in loops) if s]
    text = f'''/* Graphics quality (graphics.js). Generated by tools/build-performance-css.py: do not edit by hand.
   Balanced and Low put gi-gfx-balanced on <body>; Low adds gi-gfx-low as well. */

/* Balanced and Low: no frosted glass. A blur of what is behind a panel is repainted whenever anything
   under it changes, and without a graphics card it is drawn on the processor. Panels keep their tint. */
{(",\n").join(blur)} {{
    -webkit-backdrop-filter: none !important;
    backdrop-filter: none !important;
}}

/* Low: looping glows, pulses and bobbing stop. Only animations that are nothing but a loop are listed,
   so nothing that waits for an animation to finish is affected. */
{(",\n").join(loop)} {{
    animation: none !important;
}}
'''
    (EXT / OUT).write_text(text)
    print(f'{OUT}: {len(blur)} blurred surfaces, {len(loop)} looping animations')


if __name__ == '__main__':
    main()
